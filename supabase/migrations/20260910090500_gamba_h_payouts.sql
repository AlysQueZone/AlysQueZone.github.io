-- Ребаланс пивкойнов, тикет 07: Гамба H — возврат частоты плюсов без станка.
-- Диагноз: таблица G балансна (EV 97.5), но убивает фан — 82% спинов дают ≤ 0
-- (мимо 52 + возврат 30 с net 0), в плюсе только 18% против 70% у таблицы F.
-- Гриллинг 2026-09-10 (Q1–Q7): фан = частота, EV держим, x10 жив, ставка 100.
-- Таблица H: мимо 52% → 0, возврат 10% → 100 (при своих), мелочь 30% → 150 (+50),
-- крупно 5% → 250 (+150), джекпот x10 3% → 1000.
-- EV = (10*100 + 30*150 + 5*250 + 3*1000)/100 = 9750/100 = 97.5 — как у G.
-- Доля «в плюсе» 18% → 38%; пустых 82% → 62%; мимо не тронуто.
-- RPC spin_gamba НЕ меняется — исход считается по конфигу из
-- public.gamba_payouts (взвешенный ролл по weight, порядок — по payout),
-- новый конфиг подхватится сам. Номинал 150 и исход 'small' уже валидны
-- в CHECK (история F) — ALTER не нужен.
-- Применить: мёрж в main применит сам; руками на прод НЕ накатывать.

-- Новый seed таблицы H (старые строки не UPDATE — только DELETE+INSERT).
delete from public.gamba_payouts
where outcome in ('miss', 'small', 'big', 'jackpot', 'return');

insert into public.gamba_payouts (outcome, payout, weight, label) values
  ('miss', 0, 52, 'мимо'),
  ('return', 100, 10, 'возврат 100'),
  ('small', 150, 30, '+50'),
  ('big', 250, 5, '+150'),
  ('jackpot', 1000, 3, 'джекпот x10');
