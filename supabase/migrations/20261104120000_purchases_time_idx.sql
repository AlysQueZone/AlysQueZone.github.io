-- Индекс времени для «Лога сделок» (/deals/): страница читает всю биржу
-- свежими сверху, keyset по паре `(created_at, id)`. Без индекса каждый запрос
-- сканировал бы `purchases` целиком и сортировал её, а с ростом истории это
-- дороже и дольше каждой прокрутки.
--
-- Гранты, RLS и колонки не меняем: публичный SELECT из `purchases` уже открыт,
-- новых объектов, кроме индекса, нет. Математика (цена, комиссия, роялти) не
-- тронута.
-- Применить: мёрж в main применит сам; руками на прод НЕ накатывать.

create index if not exists purchases_time_idx
  on public.purchases (created_at desc, id desc);
