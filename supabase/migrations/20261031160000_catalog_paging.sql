-- Витрина листается страницами (решение — docs/adr/0012): `/lots/` читает
-- загруженное окно, а не весь каталог. Ключ страницы — keyset по паре
-- `(price, slug)`: цена растёт от перекупов, slug добивает ничью и держит
-- границу на месте (offset бы сдвигался живыми вставками). «Мои приветы» —
-- отдельный полный запрос владельца, поэтому ему нужен поиск по owner_uid.
--
-- Гранты и RLS не меняем: новых объектов, кроме индексов, нет. Математика
-- (цена, комиссия, роялти) не тронута.
-- Применить: мёрж в main применит сам; руками на прод НЕ накатывать.

-- 1. Порядок витрины: выборка следующей страницы после `(price, slug)`.
create index if not exists lots_price_slug_idx on public.lots (price, slug);

-- 2. «Мои приветы»: полный список лотов владельца (не окно страницы).
create index if not exists lots_owner_uid_idx on public.lots (owner_uid)
  where owner_uid is not null;
